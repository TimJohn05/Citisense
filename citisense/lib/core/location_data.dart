  static String? findCityForBarangay(String barangay) {
    final bLower = barangay.trim().toLowerCase();
    for (final entry in citiesAndBarangays.entries) {
      for (final b in entry.value) {
        if (b.toLowerCase() == bLower) {
          return entry.key;
        }
      }
    }
    return null;
  }
